-- 08: model evaluation against synthetic ground truth (evaluation only - never a model or agent input)
-- Event-level: was each test-period failure flagged with the right mode in the 7 days before it, and how early?

USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE TABLE PDM_DB.ML.TEST_SCORES AS
SELECT MACHINE_ID, HOUR_TS, LABEL,
       PDM_DB.ML.FAILURE_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(* EXCLUDE (MACHINE_ID, HOUR_TS, LINE_ID, PLANT_ID, POWER_FEED_ID, LABEL))) AS P
FROM PDM_DB.ML.TEST_V;

CREATE OR REPLACE VIEW PDM_DB.ML.TEST_FLAGS AS
SELECT s.MACHINE_ID, s.HOUR_TS, 1 - COALESCE(ANY_VALUE(s.P:probability:NONE::FLOAT), 0) AS RISK,
       MAX_BY(k.KEY, k.VALUE::FLOAT) AS TOP_MODE
FROM PDM_DB.ML.TEST_SCORES s, LATERAL FLATTEN(INPUT => s.P:probability) k
WHERE k.KEY <> 'NONE'
GROUP BY s.MACHINE_ID, s.HOUR_TS;

-- Rule-based detections (same rules as REFRESH_ALERTS) for modes the model does not cover
CREATE OR REPLACE VIEW PDM_DB.ML.TEST_RULE_FLAGS AS
SELECT MACHINE_ID, HOUR_TS, 'POWER_SHOCK' AS MODE FROM PDM_DB.ML.FEATURES_V
 WHERE HOUR_TS >= '2026-09-15' AND (UNPROTECTED_SPIKES_72H > 0 OR INRUSH_72H > 0)
UNION ALL
SELECT c.MACHINE_ID, DATE_TRUNC('HOUR', h.STATUS_TS), 'REDUNDANCY_LOSS'
FROM PDM_DB.RAW.COMPONENT_HEALTH h JOIN PDM_DB.RAW.COMPONENTS c ON c.COMPONENT_ID = h.COMPONENT_ID
WHERE c.REDUNDANCY_GROUP IS NOT NULL AND h.STATUS IN ('FAILED', 'DEGRADED');

CREATE OR REPLACE TABLE PDM_DB.ML.MODEL_EVAL_EVENTS
  COMMENT = 'One row per ground-truth failure in the test window: detected?, lead time, detector'
AS
WITH gt AS (
  SELECT * FROM PDM_DB.ML.SYNTH_GROUND_TRUTH WHERE FAILURE_TS >= '2026-09-16' OR IS_FUTURE
), model_hit AS (
  SELECT g.MACHINE_ID, g.FAILURE_TS, MIN(f.HOUR_TS) AS FIRST_FLAG
  FROM gt g JOIN PDM_DB.ML.TEST_FLAGS f
    ON f.MACHINE_ID = g.MACHINE_ID AND f.TOP_MODE = g.FAILURE_MODE AND f.RISK >= 0.5
   AND f.HOUR_TS >= DATEADD('DAY', -7, g.FAILURE_TS) AND f.HOUR_TS < g.FAILURE_TS
  GROUP BY 1, 2
), rule_hit AS (
  SELECT g.MACHINE_ID, g.FAILURE_TS, MIN(r.HOUR_TS) AS FIRST_FLAG
  FROM gt g JOIN PDM_DB.ML.TEST_RULE_FLAGS r
    ON r.MACHINE_ID = g.MACHINE_ID AND r.MODE = g.FAILURE_MODE
   AND r.HOUR_TS >= DATEADD('DAY', -21, g.FAILURE_TS) AND r.HOUR_TS < g.FAILURE_TS
  GROUP BY 1, 2
)
SELECT g.MACHINE_ID, g.FAILURE_MODE, g.SUB_MODE, g.FAILURE_TS, g.IS_FUTURE, g.COMPONENT_ID,
       COALESCE(m.FIRST_FLAG, r.FIRST_FLAG) AS FIRST_FLAG,
       CASE WHEN m.FIRST_FLAG IS NOT NULL THEN 'MODEL' WHEN r.FIRST_FLAG IS NOT NULL THEN 'RULE' ELSE 'MISSED' END AS DETECTED_BY,
       ROUND(DATEDIFF('MINUTE', COALESCE(m.FIRST_FLAG, r.FIRST_FLAG), g.FAILURE_TS) / 60, 1) AS LEAD_TIME_HOURS
FROM gt g
LEFT JOIN model_hit m ON m.MACHINE_ID = g.MACHINE_ID AND m.FAILURE_TS = g.FAILURE_TS
LEFT JOIN rule_hit r  ON r.MACHINE_ID = g.MACHINE_ID AND r.FAILURE_TS = g.FAILURE_TS;

CREATE OR REPLACE TABLE PDM_DB.ML.MODEL_EVALUATION
  COMMENT = 'Per failure mode: events, detected, recall, median lead time; plus false-alarm hours'
AS
SELECT FAILURE_MODE AS METRIC_GROUP, COUNT(*) AS EVENTS, COUNT_IF(DETECTED_BY <> 'MISSED') AS DETECTED,
       ROUND(DETECTED / NULLIF(EVENTS, 0), 3) AS RECALL,
       MEDIAN(LEAD_TIME_HOURS) AS MEDIAN_LEAD_HOURS, LISTAGG(DISTINCT DETECTED_BY, ', ') AS DETECTED_BY
FROM PDM_DB.ML.MODEL_EVAL_EVENTS GROUP BY 1
UNION ALL
SELECT 'ALL', COUNT(*), COUNT_IF(DETECTED_BY <> 'MISSED'), ROUND(COUNT_IF(DETECTED_BY <> 'MISSED') / COUNT(*), 3),
       MEDIAN(LEAD_TIME_HOURS), NULL
FROM PDM_DB.ML.MODEL_EVAL_EVENTS
UNION ALL
-- false alarms: model-flagged hours with no ground-truth failure of any mode on that machine in the next 7 days
SELECT 'FALSE_ALARM_HOURS', COUNT(*), NULL, ROUND(COUNT(*) / (SELECT COUNT(*) FROM PDM_DB.ML.TEST_FLAGS), 4), NULL,
       COUNT(DISTINCT MACHINE_ID) || ' machines'
FROM (
  SELECT f.MACHINE_ID, f.HOUR_TS
  FROM PDM_DB.ML.TEST_FLAGS f
  LEFT JOIN PDM_DB.ML.SYNTH_GROUND_TRUTH g
    ON g.MACHINE_ID = f.MACHINE_ID AND g.FAILURE_TS > f.HOUR_TS AND g.FAILURE_TS <= DATEADD('DAY', 7, f.HOUR_TS)
  WHERE f.RISK >= 0.5
  GROUP BY f.MACHINE_ID, f.HOUR_TS
  HAVING COUNT(g.MACHINE_ID) = 0
);
